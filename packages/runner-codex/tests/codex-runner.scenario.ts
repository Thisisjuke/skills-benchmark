// Registered by the Codex provider scenario suite.
import { existsSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { describe, expect, it } from "vite-plus/test";

import { CodexRunner } from "@skillbench/runner-codex";
import { verifyRunnerContract } from "@skillbench/test-contracts";
import {
  MOCK_EXECUTION_PROFILE,
  type ExecutionProfile,
  type RunInput,
} from "@skillbench/sdk/runners";
import { LocalSourceResolver } from "@skillbench/sdk/sources/local";

const policy = { maxFileSizeBytes: 1_000_000, maxSnapshotSizeBytes: 5_000_000 };
const fakeCodex = resolve("tests/fixtures/fake-codex.ts");
const executionProfile = {
  runner: "codex" as const,
  runnerVersion: "codex-cli 0.153.0",
  model: "gpt-test",
  reasoningEffort: "low" as const,
};

async function input(
  timeoutMs = 1_000,
  profile: ExecutionProfile = executionProfile,
): Promise<RunInput> {
  const resolved = await new LocalSourceResolver(policy).resolve(
    "../sdk/tests/fixtures/skills/basic",
  );
  const parent = mkdtempSync(join(tmpdir(), "skillbench-codex-runner-"));
  return {
    runId: "run",
    evalCaseId: "case",
    repetition: 1,
    snapshot: resolved.snapshot,
    prompt: "Do the task; this text is one argv.",
    fixtures: [],
    timeoutMs,
    workspacePath: join(parent, "attempt"),
    permissions: { schemaVersion: 1, sandbox: "workspace-write" },
    executionProfile: profile,
  };
}

function runner(mode: string, maxOutputBytes = 1024 * 1024): CodexRunner {
  return new CodexRunner({
    executable: process.execPath,
    executableArgs: [fakeCodex],
    maxOutputBytes,
    environment: { SKILLBENCH_FAKE_CODEX_MODE: mode },
  });
}

describe("CodexRunner", () => {
  it("satisfies the reusable runner contract", async () => {
    await verifyRunnerContract({
      runner: runner("success"),
      runnerName: "codex",
      executionProfile,
      mismatchedProfile: MOCK_EXECUTION_PROFILE,
      createInput: (profile) => input(1_000, profile),
    });
  });

  it("runs an argv-only Codex process, parses JSONL and captures changed files", async () => {
    const runInput = await input();
    const result = await runner("success").run(runInput);

    expect(result).toMatchObject({
      status: "completed",
      exitCode: 0,
      stdout: "FAKE_CODEX_OK",
      stderr: "",
      tokens: { input: 13, output: 5 },
    });
    expect(result.artifacts).toEqual([
      expect.objectContaining({ relativePath: "argv.json" }),
      expect.objectContaining({ relativePath: "generated.txt", sizeBytes: 24 }),
    ]);
    expect(readFileSync(join(runInput.workspacePath, "generated.txt"), "utf8")).toBe(
      "generated by fake Codex\n",
    );
    expect(existsSync(join(runInput.workspacePath, ".skillbench", "run.json"))).toBe(true);
    expect(result).not.toHaveProperty("skillActivated");
    expect(result.trace).toMatchObject({
      protocol: "codex-exec-jsonl-v1",
      version: "codex-cli 0.153.0",
      executionProfile,
      threadId: "fake-thread",
      stdoutTruncated: false,
      stderrTruncated: false,
    });
    const argv = JSON.parse(
      readFileSync(join(runInput.workspacePath, "argv.json"), "utf8"),
    ) as string[];
    expect(argv.at(-1)).toBe(runInput.prompt);
    expect(argv).toContain("--ignore-user-config");
    expect(argv).toContain("--ignore-rules");
    expect(argv).toContain("--ephemeral");
    expect(argv).toContain("--model");
    expect(argv).toContain("gpt-test");
    expect(argv).toContain("-c");
    expect(argv).toContain('model_reasoning_effort="low"');
  });

  it("returns failed for non-zero exits and signals", async () => {
    const nonzero = await runner("nonzero").run(await input());
    expect(nonzero).toMatchObject({ status: "failed", exitCode: 7 });
    expect(nonzero.stderr).toContain("fake codex failure");

    const signaled = await runner("signal").run(await input());
    expect(signaled.status).toBe("failed");
    expect(signaled.exitCode).not.toBe(0);
  });

  it("terminates on timeout and keeps output bounded", async () => {
    const timedOut = await runner("timeout").run(await input(30));
    expect(timedOut).toMatchObject({ status: "timed-out", exitCode: null });

    const bounded = await runner("large", 256).run(await input());
    expect(new TextEncoder().encode(bounded.stderr).byteLength).toBeLessThanOrEqual(256);
    expect(bounded.trace).toMatchObject({ stderrTruncated: true });
  });

  it("terminates the Codex subprocess when its cancellation signal aborts", async () => {
    const controller = new AbortController();
    const runInput = await input(5_000);
    const execution = runner("timeout").run({ ...runInput, signal: controller.signal });
    setTimeout(() => controller.abort(new Error("cancelled by test")), 25);

    await expect(execution).rejects.toThrow("cancelled by test");
  });

  it("rejects a missing executable and an incompatible successful protocol", async () => {
    const missing = new CodexRunner({ executable: "/definitely/missing/codex" });
    await expect(missing.version()).rejects.toMatchObject({ code: "CODEX_NOT_FOUND" });

    const incompatible = await runner("incompatible").run(await input());
    expect(incompatible).toMatchObject({ status: "failed", exitCode: 0 });
    expect(incompatible.stderr).toContain("without a turn.completed JSONL event");
  });
});
